//! Named terms for the lambda calculus implementation.
//!
//! This module defines a small, named representation for lambda terms using a fixed
//! set of variable names. It is useful for debugging, tests, and examples where
//! explicit named variables are easier to read than de Bruijn indices.

/// A small set of named variables used in the named lambda term representation.
///
/// This enum supports a simple named representation of lambda calculus terms
/// where variable names are fixed to `x` and `y`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Name {
    /// The first named variable, printed as `x`.
    X,
    /// The second named variable, printed as `y`.
    Y,
}

/// A named lambda calculus term using explicit variable names.
///
/// This enum represents variables, abstractions, and applications in a
/// readable named form, rather than using de Bruijn indices.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum NamedTerm {
    /// A variable reference.
    Var(Name),
    /// A lambda abstraction with a named parameter and body.
    Lam(Name, Box<NamedTerm>),
    /// A function application of one named term to another.
    App(Box<NamedTerm>, Box<NamedTerm>),
}

impl std::fmt::Display for Name {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Name::X => write!(f, "x"),
            Name::Y => write!(f, "y"),
        }
    }
}

impl std::fmt::Display for NamedTerm {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            NamedTerm::Var(v) => write!(f, "{v}"),
            NamedTerm::Lam(v, body) => write!(f, "λ{}. ({})", v, body),
            NamedTerm::App(l, r) => write!(f, "(({}) ({}))", l, r),
        }
    }
}

use crate::Term;

fn convert_impl(term: &Term, stack: &mut Vec<Name>) -> Option<NamedTerm> {
    match term {
        Term::Var(i) => {
            if *i >= stack.len() {
                return None;
            }

            let idx = stack.len() - 1 - i;
            let name = stack[idx];

            // No nearer binder may have the same name.
            for j in idx + 1..stack.len() {
                if stack[j] == name {
                    return None;
                }
            }

            Some(NamedTerm::Var(name))
        }

        Term::App(lr) => {
            let (l, r) = &**lr;
            Some(NamedTerm::App(
                Box::new(convert_impl(l, stack)?),
                Box::new(convert_impl(r, stack)?),
            ))
        }

        Term::Abs(body) => {
            for name in [Name::X, Name::Y] {
                stack.push(name);

                if let Some(body) = convert_impl(body, stack) {
                    stack.pop();
                    return Some(NamedTerm::Lam(name, Box::new(body)));
                }

                stack.pop();
            }

            None
        }
    }
}

impl Term {
    /// Attempts to convert a de Bruijn-indexed lambda term into an α-equivalent
    /// named representation using **only the variable names `x` and `y`**.
    ///
    /// The conversion assigns either `x` or `y` to each lambda binder while
    /// preserving the binding structure of the original de Bruijn term.
    ///
    /// Returns:
    ///
    /// - `Some(named_term)` if a valid assignment of `x` and `y` exists.
    /// - `None` if no such assignment exists, or if the input contains an
    ///   out-of-scope de Bruijn index.
    ///
    /// # Examples
    ///
    /// ```text
    /// λλλ0
    ///     ↓
    /// λx. λy. λx. x
    /// ```
    ///
    /// ```text
    /// λ(λ(λ1)01)0
    ///     ↓
    /// λx. (λy. ((λx. y) y x)) x
    /// ```
    ///
    /// # Note
    ///
    /// The returned names are not unique. Multiple α-equivalent results may exist;
    /// this function returns one valid assignment.
    pub fn convert(&self) -> Option<NamedTerm> {
        convert_impl(self, &mut Vec::new())
    }
}

